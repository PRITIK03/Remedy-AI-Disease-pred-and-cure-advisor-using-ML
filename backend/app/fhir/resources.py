META_SOURCE = f"urn:remedy-ai:{GENERATOR.lower()}"


def meta_tag(last_updated: str | None = None) -> dict[str, object]:
    """`meta` block stamped on every generated resource."""
    return {
        "versionId": "1",
        "lastUpdated": last_updated,
        "source": META_SOURCE,
        "profile": [f"urn:remedy-ai:profile:{GENERATOR.lower()}"],
        "tag": [
            {
                "system": META_SOURCE,
                "code": "generated",
                "display": GENERATED_TAG,
            }
        ],
    }



def categorical_display(feature: str, value: int) -> str:
    """Human-readable display for the categorical assessment encodings.

    These are the model's *encodings*; the wording says so explicitly so a
    downstream system is never misled into thinking this is a clinical
    measurement vocabulary.
    """
    value = int(value)
    if feature == "cp":
        return {
            0: "Typical angina (model category 0)",
            1: "Atypical angina (model category 1)",
            2: "Non-anginal pain (model category 2)",
            3: "Asymptomatic (model category 3)",
        }.get(value, f"Unknown category ({value})")
    if feature == "restecg":
        return {
            0: "Normal (model category 0)",
            1: "ST-T wave abnormality (model category 1)",
            2: "Left ventricular hypertrophy probable/definite (model category 2)",
        }.get(value, f"Unknown category ({value})")
    if feature == "slope":
        return {
            0: "Upsloping (model category 0)",
            1: "Flat (model category 1)",
            2: "Downsloping (model category 2)",
        }.get(value, f"Unknown category ({value})")
    if feature == "ca":
        return f"{value} major vessel(s) (model category {value})"
    if feature == "thal":
        return {
            0: "Unknown/normal (model category 0)",
            1: "Fixed defect (model category 1)",
            2: "Reversible defect (model category 2)",
            3: "Other abnormality (model category 3)",
        }.get(value, f"Unknown category ({value})")
    if feature in ("sex", "fbs", "exang"):
        return {0: "No", 1: "Yes"}.get(value, f"Unknown ({value})")
    return str(value)


